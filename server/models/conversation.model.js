const mongoose = require('mongoose')

const ObjectId = mongoose.Schema.ObjectId

const reactionSchema = new mongoose.Schema({
    userId : { type : ObjectId, ref : 'User', required : true },
    emoji : { type : String, required : true }
},{ _id : false })

const receiptSchema = new mongoose.Schema({
    userId : { type : ObjectId, ref : 'User', required : true },
    at : { type : Date, required : true }
},{ _id : false })

const pollVoteSchema = new mongoose.Schema({
    userId : { type : ObjectId, ref : 'User', required : true },
    options : { type : [Number], default : [] },
    at : { type : Date }
},{ _id : false })

const messageSchema = new mongoose.Schema({
    conversationId : {
        type : ObjectId,
        ref : 'Conversation'
    },
    // id generated by the sending client; used to de-duplicate retries
    clientId : {
        type : String
    },
    text : {
        type : String,
        default : ""
    },
    imageUrl : {
        type : String,
        default : ""
    },
    videoUrl : {
        type : String,
        default : ""
    },
    // sticker (animated Noto emoji or your own image), shown without a bubble
    stickerUrl : { type : String, default : "" },
    // voice message
    audioUrl : { type : String, default : "" },
    audioDuration : { type : Number, default : 0 },          // seconds
    audioWaveform : { type : [Number], default : undefined }, // ~40 levels between 0 and 1, drawn as bars
    // documents / other attachments
    fileUrl : { type : String, default : "" },
    fileName : { type : String, default : "" },
    fileSize : { type : Number, default : 0 },
    fileType : { type : String, default : "" },

    // kept for backwards compatibility: true once the recipient has read the message
    seen : {
        type : Boolean,
        default : false
    },
    deliveredAt : { type : Date },
    seenAt : { type : Date },

    msgByUserId : {
        type : ObjectId,
        required : true,
        ref : 'User'
    },
    replyTo : { type : ObjectId, ref : 'Message' },
    forwarded : { type : Boolean, default : false },

    editedAt : { type : Date },

    deletedForEveryone : { type : Boolean, default : false },
    deletedAt : { type : Date },
    // users who deleted this message "for me"
    deletedFor : [{ type : ObjectId, ref : 'User' }],

    reactions : [reactionSchema],
    starredBy : [{ type : ObjectId, ref : 'User' }],

    pinned : { type : Boolean, default : false },
    pinnedAt : { type : Date },
    pinnedBy : { type : ObjectId, ref : 'User' },

    // disappearing messages: MongoDB removes the document after this date (TTL index)
    expiresAt : { type : Date },

    // ----- group chats -----
    // members who should receive this message (snapshot at send time); used for group ticks
    // (default undefined keeps one-to-one messages free of empty arrays)
    recipients : { type : [{ type : ObjectId, ref : 'User' }], default : undefined },
    deliveredTo : { type : [receiptSchema], default : undefined },
    readBy : { type : [receiptSchema], default : undefined },
    // call history entry ("Missed voice call", "Video call 2:31"); msgByUserId = the caller
    call : {
        media : { type : String, enum : ['audio', 'video'] }, // ("type" is reserved by mongoose)
        status : { type : String, enum : ['answered', 'missed', 'declined'] },
        duration : { type : Number }, // seconds, for answered calls
        participants : { type : Number } // group calls: how many people joined
    },
    // @mentions in group messages (ids of members mentioned in the text)
    mentions : { type : [{ type : ObjectId, ref : 'User' }], default : undefined },
    // poll: question + options; every voter's current choice (indexes into options)
    poll : {
        question : { type : String },
        options : { type : [String], default : undefined },
        multiple : { type : Boolean },
        votes : { type : [pollVoteSchema], default : undefined }
    },
    // preview of the first link in the text, fetched by the server after sending
    linkPreview : {
        url : String, title : String, description : String, image : String, siteName : String
    },
    // end-to-end encrypted content: { v, from, dev, to, cid, t, iv, ct, sig, keys:[{ u, d, epk, iv, wk }] }.
    // The server can't read it: text, media links + keys, poll text, contact, location and link preview are all inside.
    e2ee : { type : mongoose.Schema.Types.Mixed },
    // coarse type of an encrypted message (image / video / file / audio / sticker / poll / contact / location / text / link)
    // so "Media, links and docs" and validation keep working without the server seeing the content
    e2eeKind : { type : String },
    viewOnceKind : { type : String },
    // photo / video that can be opened once by each recipient
    viewOnce : { type : Boolean },
    // delivered without sound / notification
    silent : { type : Boolean },
    viewedBy : { type : [{ type : ObjectId, ref : 'User' }], default : undefined },
    // shared contact card
    contact : { userId : { type : ObjectId, ref : 'User' }, name : String, phone : String, email : String },
    // shared location
    location : { lat : Number, lng : Number, name : String },
    // reply to someone's status (snapshot, statuses disappear after 24 hours)
    statusReply : { statusId : ObjectId, ownerId : ObjectId, kind : String, text : String, mediaUrl : String, background : String, e2ee : mongoose.Schema.Types.Mixed },
    // an admin deleted someone else's message for everyone
    deletedByAdmin : { type : Boolean, default : false },
    // grey notice in the chat, e.g. "Alice added Bob". Names are a snapshot so they survive members leaving.
    system : {
        action : { type : String },
        actor : { id : String, name : String },
        targets : { type : [{ id : String, name : String, _id : false }], default : undefined },
        value : { type : String }
    }
},{
    timestamps : true
})

messageSchema.index({ conversationId : 1, createdAt : -1 })
messageSchema.index(
    { msgByUserId : 1, clientId : 1 },
    { unique : true, partialFilterExpression : { clientId : { $type : 'string' } } }
)
messageSchema.index({ expiresAt : 1 }, { expireAfterSeconds : 0 })
messageSchema.index({ starredBy : 1 })
messageSchema.index({ conversationId : 1, 'call.media' : 1 }, { partialFilterExpression : { 'call.media' : { $exists : true } } })
messageSchema.index({ recipients : 1, createdAt : -1 }, { partialFilterExpression : { 'recipients.0' : { $exists : true } } })

// per-user settings for a conversation (archive, pin, mute, clear, delete-for-me)
const userStateSchema = new mongoose.Schema({
    userId : { type : ObjectId, ref : 'User', required : true },
    archived : { type : Boolean, default : false },
    pinned : { type : Boolean, default : false },
    pinnedAt : { type : Date },
    muted : { type : Boolean, default : false },
    markedUnread : { type : Boolean, default : false },
    // muted until this date (no date = muted until unmuted, like "Always")
    mutedUntil : { type : Date },
    favorite : { type : Boolean, default : false },
    // hidden behind the chat lock secret code
    locked : { type : Boolean, default : false },
    // private note about this chat, only visible to this user
    note : { type : String, default : '', maxlength : 2000 },
    // messages created before this date are hidden for this user ("clear chat")
    clearedAt : { type : Date },
    // conversation hidden from this user's list until a newer message arrives ("delete chat")
    hiddenAt : { type : Date }
},{ _id : false })

const memberSchema = new mongoose.Schema({
    userId : { type : ObjectId, ref : 'User', required : true },
    role : { type : String, enum : ['admin', 'member'], default : 'member' },
    joinedAt : { type : Date, required : true },
    addedBy : { type : ObjectId, ref : 'User' }
},{ _id : false })

// someone who left or was removed: they keep read-only access to messages from their membership period
const pastMemberSchema = new mongoose.Schema({
    userId : { type : ObjectId, ref : 'User', required : true },
    joinedAt : { type : Date, required : true },
    leftAt : { type : Date, required : true },
    removed : { type : Boolean, default : false }
},{ _id : false })

const permission = { type : String, enum : ['all', 'admins'] }

const conversationSchema = new mongoose.Schema({
    // one-to-one chats: the two people. Groups don't use these.
    sender : {
        type : ObjectId,
        required : function () { return !this.isGroup },
        ref : 'User'
    },
    receiver : {
        type : ObjectId,
        required : function () { return !this.isGroup },
        ref : 'User'
    },

    // ----- group chats -----
    // 1:1 chat started by someone who isn't in this user's contacts: shown under "Message requests" until accepted
    requestFor : { type : ObjectId, ref : 'User' },

    isGroup : { type : Boolean, default : false },
    name : { type : String, trim : true, maxlength : 100 },
    description : { type : String, default : '', maxlength : 512 },
    avatar : { type : String, default : '' },
    createdBy : { type : ObjectId, ref : 'User' },
    members : [memberSchema],
    pastMembers : [pastMemberSchema],
    settings : {
        editInfo : { ...permission, default : 'all' },      // name, icon, description, disappearing, pins
        sendMessages : { ...permission, default : 'all' },
        addMembers : { ...permission, default : 'admins' }
    },

    messages : [
        {
            type : ObjectId,
            ref : 'Message'
        }
    ],
    userState : [userStateSchema],
    // group invite link code (anyone with the link can join)
    inviteCode : { type : String },
    // disappearing messages timer in seconds (0 = off)
    disappearAfter : { type : Number, default : 0 },
    lastMessageAt : { type : Date }
},{
    timestamps : true
})

conversationSchema.index({ sender : 1, receiver : 1 })
conversationSchema.index({ receiver : 1 })
conversationSchema.index({ 'members.userId' : 1 })
conversationSchema.index({ 'pastMembers.userId' : 1 })
conversationSchema.index({ inviteCode : 1 }, { unique : true, partialFilterExpression : { inviteCode : { $type : 'string' } } })

const MessageModel = mongoose.model('Message',messageSchema)
const ConversationModel = mongoose.model('Conversation',conversationSchema)

module.exports = {
    MessageModel,
    ConversationModel
}
